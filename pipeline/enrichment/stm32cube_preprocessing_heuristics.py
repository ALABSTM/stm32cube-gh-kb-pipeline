from typing import List


def detect_layer(text: str) -> str:
    if not text:
        return "Other"

    txt = text.upper()

    if "HAL_" in txt or " HAL DRIVER" in txt or " HAL LIBRARY" in txt:
        return "HAL"

    if "LL_" in txt or " LOW LAYER" in txt or "LOW-LAYER" in txt:
        return "LL"

    middleware_keywords = [
        "LWIP",
        "FATFS",
        "FAT FS",
        "FREERTOS",
        "USB HOST",
        "USB DEVICE",
        "USBH_",
        "USBD_",
        "MIDDLEWARE",
        "TCP/IP",
        "TCP IP",
    ]
    if any(kw in txt for kw in middleware_keywords):
        return "Middleware"

    cubemx_keywords = [
        "CUBEMX",
        "STM32CUBEMX",
        " MX_",
        "GENERATED BY STM32CUBEMX",
        "DEVICE CONFIGURATION TOOL",
    ]
    if any(kw in txt for kw in cubemx_keywords):
        return "CubeMX"

    return "Other"


def detect_severity(text: str, labels: List[str] | None = None) -> str:
    if labels is None:
        labels = []

    labels_lower = [lbl.lower() for lbl in labels]
    txt_lower = (text or "").lower()

    low_keywords = [
        "documentation",
        "doc issue",
        "doc problem",
        "typo",
        "spelling",
        "comment typo",
        "example description",
        "minor issue",
        "cosmetic",
    ]
    low_labels = ["documentation", "doc", "typo"]

    if any(lbl in labels_lower for lbl in low_labels) or any(kw in txt_lower for kw in low_keywords):
        return "low"

    high_keywords = [
        "hardfault",
        "hard fault",
        "crash",
        "crashes",
        "freeze",
        "frozen",
        "hang",
        "stuck",
        "blocking",
        "block forever",
        "deadlock",
        "data corruption",
        "corrupted data",
        "doesn't start",
        "does not start",
        "cannot start",
        "no communication",
        "watchdog reset",
        "wdg reset",
        "reset loop",
        "infinite loop",
        "regression",
    ]

    for kw in high_keywords:
        if kw in txt_lower:
            return "high"

    return "medium"
