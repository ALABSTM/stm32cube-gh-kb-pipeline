from typing import List, Any


def detect_layer(text: str) -> str:
    """
    Détecte la couche logicielle principale concernée par l'issue.

    Retourne une des valeurs :
    - "HAL"
    - "LL"
    - "Middleware"
    - "CubeMX"
    - "Other"
    """
    if not text:
        return "Other"

    txt = text.upper()

    # HAL
    if "HAL_" in txt or " HAL DRIVER" in txt or " HAL LIBRARY" in txt:
        return "HAL"

    # LL (Low Layer)
    if "LL_" in txt or " LOW LAYER" in txt or "LOW-LAYER" in txt:
        return "LL"

    # Middleware
    middleware_keywords = [
        "LWIP",
        "FATFS",
        "FAT FS",
        "FREERTOS",
        "USB HOST",
        "USB DEVICE",
        "USBH_",
        "USBD_",
        "MIDDLEWARE",
        "TCP/IP",
        "TCP IP",
    ]
    if any(kw in txt for kw in middleware_keywords):
        return "Middleware"

    # CubeMX
    cubemx_keywords = [
        "CUBEMX",
        "STM32CUBEMX",
        " MX_",
        "GENERATED BY STM32CUBEMX",
        "DEVICE CONFIGURATION TOOL",
    ]
    if any(kw in txt for kw in cubemx_keywords):
        return "CubeMX"

    return "Other"


from typing import List


def detect_severity(text: str, labels: List[str] | None = None) -> str:
    """
    Estimation heuristique de la sévérité de l'issue : "low", "medium" ou "high".
    """
    if labels is None:
        labels = []

    labels_lower = [lbl.lower() for lbl in labels]
    txt_lower = (text or "").lower()

    # Low severity : doc / typo / minor
    low_keywords = [
        "documentation",
        "doc issue",
        "doc problem",
        "typo",
        "spelling",
        "comment typo",
        "example description",
        "minor issue",
        "cosmetic",
    ]
    low_labels = ["documentation", "doc", "typo"]

    if any(lbl in labels_lower for lbl in low_labels) or any(
        kw in txt_lower for kw in low_keywords
    ):
        return "low"

    # High severity : crash, hardfault, freeze, blocking...
    high_keywords = [
        "hardfault",
        "hard fault",
        "crash",
        "crashes",
        "freeze",
        "frozen",
        "hang",
        "stuck",
        "blocking",
        "block forever",
        "deadlock",
        "data corruption",
        "corrupted data",
        "doesn't start",
        "does not start",
        "cannot start",
        "no communication",
        "watchdog reset",
        "wdg reset",
        "reset loop",
        "infinite loop",
        "regression",
    ]

    for kw in high_keywords:
        if kw in txt_lower:
            return "high"

    # Par défaut
    return "medium"


